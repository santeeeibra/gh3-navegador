import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import crypto from 'node:crypto';

const base = 'https://nvlwlmyuqorxaupcdbdb.supabase.co';
const origin = 'https://lasvegasherogame.com';
const source = await fs.readFile('tools/analytics/feedback/gh3-feedback.js', 'utf8');
const publicKey = source.match(/const publicKey = '([^']+)'/)?.[1];
assert.ok(publicKey);
const access = await fs.readFile('artifacts/analytics/PANEL-ACCESS-LOCAL.md', 'utf8');
const admin = access.match(/Contraseña: `([^`]+)`/)?.[1];
assert.ok(admin?.length >= 32);
const headers = { origin, apikey: publicKey, authorization: `Bearer ${publicKey}`, 'content-type': 'application/json' };
const endpoint = base + '/functions/v1/gh3-feedback';
const send = (body, extra = {}) => fetch(endpoint, { method: 'POST', headers, body: JSON.stringify(body), signal: AbortSignal.timeout(30000), ...extra });
const ids = Array.from({ length: 5 }, () => crypto.randomUUID());
const report = { request_ids: ids, api: {}, generated_at: new Date().toISOString() };
await fs.mkdir('artifacts/feedback', { recursive: true });
await fs.writeFile('artifacts/feedback/api-smoke.json', JSON.stringify(report, null, 2));
const body = id => ({ request_id: id, rating: 3, category: 'general', message: 'Prueba técnica temporal Codex — borrar sólo esta fila al terminar la verificación.', nickname: 'Codex prueba', device: 'desktop', browser: 'Edge' });
try {
  report.api.noCredential = (await send(body(ids[0]), { headers: { origin, 'content-type': 'application/json' } })).status;
  assert.equal(report.api.noCredential, 401);
  report.api.invalidRating = (await send({ ...body(ids[0]), rating: 9 })).status;
  assert.equal(report.api.invalidRating, 400);
  report.api.foreignOrigin = (await send(body(ids[0]), { headers: { ...headers, origin: 'https://evil.test' } })).status;
  assert.equal(report.api.foreignOrigin, 403);
  const preflight = await fetch(endpoint, { method: 'OPTIONS', headers: { origin, 'access-control-request-method': 'POST', 'access-control-request-headers': 'authorization,apikey,content-type' }, signal: AbortSignal.timeout(30000) });
  assert.equal(preflight.status, 204); assert.match(preflight.headers.get('access-control-allow-headers'), /authorization/);
  report.api.preflight = preflight.status;
  const submissions = await Promise.all(ids.map(id => send(body(id))));
  report.api.concurrent = submissions.map(response => response.status);
  assert.deepEqual([...report.api.concurrent].sort(), [200, 200, 200, 429, 429]);
  const storedIds = ids.filter((id, index) => submissions[index].status === 200);report.stored_request_ids = storedIds;
  report.api.duplicate = (await send(body(storedIds[0]))).status;
  assert.equal(report.api.duplicate, 200);
  const dashboard = base + '/functions/v1/gh3-analytics-dashboard?days=7';
  report.api.privateDenied = (await fetch(dashboard, { headers: { origin, authorization: `Bearer ${publicKey}` }, signal: AbortSignal.timeout(30000) })).status;
  assert.equal(report.api.privateDenied, 401);
  const read = await fetch(dashboard, { headers: { origin, authorization: `Bearer ${admin}` }, signal: AbortSignal.timeout(30000) });
  report.api.privateRead = read.status;assert.equal(read.status, 200);
  const data = await read.json();assert.ok(data.feedback.total >= 3);
  const ours = data.feedback.recent.filter(row => row.nickname === 'Codex prueba' && row.message.startsWith('Prueba técnica temporal Codex'));
  assert.equal(ours.length, 3);assert.equal(ours.every(row => row.rating === 3), true);
  assert.doesNotMatch(JSON.stringify(data), /rate_bucket|request_id|session_id/);
  report.api.publicTableRead = (await fetch(base + '/rest/v1/gh3_feedback?select=rating', { headers: { apikey: publicKey, authorization: `Bearer ${publicKey}` }, signal: AbortSignal.timeout(30000) })).status;
  assert.ok([401, 403].includes(report.api.publicTableRead));
  report.passed = true;
  console.log(JSON.stringify(report, null, 2));
} finally { await fs.writeFile('artifacts/feedback/api-smoke.json', JSON.stringify(report, null, 2)); }
