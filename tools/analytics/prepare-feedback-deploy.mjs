import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';

const root = process.cwd();
const cmd = await fs.readFile('2-PUBLICAR-GH3.cmd', 'utf8');
const source = path.resolve(cmd.match(/^set GH3_SRC=(.+)$/m)?.[1].trim() || '');
assert.ok(source.startsWith(root + path.sep));
const output = path.resolve('artifacts/privado/deploy-app/.vercel/output');
const destination = path.join(output, 'static/gh3');
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const localManifest = await fs.readFile(path.join(source, 'manifest.json'));
const liveManifest = await fetch('https://lasvegasherogame.com/gh3/manifest.json', { cache: 'no-store', signal: AbortSignal.timeout(30000) });
assert.equal(liveManifest.status, 200);
assert.equal(sha(Buffer.from(await liveManifest.arrayBuffer())), sha(localManifest), 'Manifest changed: missing/new chunks must be resolved first');
const project = JSON.parse(await fs.readFile('artifacts/privado/deploy-app/.vercel/project.json'));
assert.equal(project.projectName, 'gh3-privado');
const backup = 'artifacts/respaldo/2026-10-14-feedback/predeploy';await fs.mkdir(backup,{recursive:true});
for(const [from,name] of [[path.join(destination,'index.html'),'index.html'],[path.join(output,'config.json'),'config.json']])await fs.copyFile(from,path.join(backup,name));
const run = (file, args = [], env = {}) => execFileSync(process.execPath, [file, ...args], { stdio: 'inherit', env: { ...process.env, ...env } });
run('tools/ui3/stage-privado.mjs', [], { GH3_SRC: source, GH3_DST: destination, GH3_NO_CHUNKS: '1' });
run('tools/analytics/stage-feedback.mjs', [destination]);
run('tools/analytics/stage-dashboard.mjs', [path.join(output, 'static/estadisticas')]);
run('tools/analytics/patch-vercel-config.mjs', [output]);
const names=await fs.readdir(destination);assert.ok(names.includes('gh3-feedback.js'));
const html=await fs.readFile(path.join(destination,'index.html'),'utf8');assert.ok(html.includes('src="gh3-feedback.js"'));
assert.equal((await fs.readdir(path.join(destination,'chunks'))).length,0);
const report={source,output,manifest_sha256:sha(localManifest),wasm_sha256:sha(await fs.readFile(path.join(source,'gh3-web.wasm'))),index_sha256:sha(await fs.readFile(path.join(destination,'index.html'))),feedback_sha256:sha(await fs.readFile(path.join(destination,'gh3-feedback.js'))),chunk_count:JSON.parse(localManifest).files.flatMap(file=>file.chunks).length};
await fs.writeFile('artifacts/feedback/deploy-prepared.json',JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
