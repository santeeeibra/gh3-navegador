import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {build} from 'esbuild';
const root=path.resolve('artifacts/resolucion-interna'),out=path.join(root,'demo');
const cmd=fs.readFileSync('2-PUBLICAR-GH3.cmd','utf8');
const source=path.resolve(cmd.match(/^set GH3_SRC=(.+)$/m)[1].trim());
if(source===out)throw Error('Se requiere una copia independiente.');
const sha=file=>createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const original=Object.fromEntries(fs.readdirSync(source,{withFileTypes:true}).filter(e=>e.isFile()).map(e=>[e.name,sha(path.join(source,e.name))]));
fs.mkdirSync(out,{recursive:true});
for(const name of Object.keys(original))fs.copyFileSync(path.join(source,name),path.join(out,name));
if(!fs.existsSync(path.join(out,'chunks'))&&fs.existsSync(path.join(source,'chunks')))fs.symlinkSync(path.join(source,'chunks'),path.join(out,'chunks'),'junction');
let html=fs.readFileSync(path.join(source,'index.html'),'utf8');
if(!html.includes('src="native60-page.js"'))throw Error('La copia no usa el puente native60 esperado.');
html=html.replace(/<script src="gh3-render-scale.js"><\/script>/g,'').replace('<head>','<head><script src="gh3-render-scale.js"></script>');
fs.writeFileSync(path.join(out,'index.html'),html);
fs.copyFileSync('tools/ui-layout/render-scale.js',path.join(out,'gh3-render-scale.js'));
await build({entryPoints:['tools/r5-native60/gpu-worker.mjs'],bundle:true,format:'iife',platform:'browser',target:'es2022',outfile:path.join(out,'r5snap-native60-gpu.js')});
const changed=Object.keys(original).filter(name=>sha(path.join(out,name))!==original[name]);
if(changed.some(name=>!['index.html','r5snap-native60-gpu.js'].includes(name)))throw Error('Cambió un archivo ajeno a resolución.');
for(const [name,hash]of Object.entries(original))if(sha(path.join(source,name))!==hash)throw Error('Se modificó la copia fuente.');
const report={source,out,changed,added:['gh3-render-scale.js'],source_intact:true,engine_unchanged:['gh3-web.js','gh3-web.wasm','manifest.json'].every(name=>sha(path.join(out,name))===original[name]),engine_sha256:Object.fromEntries(['gh3-web.js','gh3-web.wasm','manifest.json'].map(name=>[name,original[name]])),published:false};
fs.writeFileSync(path.join(root,'prepared.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
